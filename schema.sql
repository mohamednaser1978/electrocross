-- =====================================================================
-- ElectroCross Database Schema (SQLite)
-- منظومة إدارة توافقية وبدائل القطع الإلكترونية لورش الصيانة
-- =====================================================================

PRAGMA foreign_keys = ON;

-- 1. Components Table (جدول القطع والمكونات الإلكترونية)
CREATE TABLE IF NOT EXISTS components (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    part_number TEXT NOT NULL UNIQUE,       -- رمز القطعة، مثل VIPer12A, OB2269CP
    package_type TEXT,                      -- نوع التغليف، مثل DIP-8, SOP-8, TO-220
    category TEXT,                          -- التصنيف، مثل PWM Controller, Power MOSFET
    description TEXT,                       -- توصيف تقني وتفاصيل القدرة والتردد
    stock_quantity INTEGER DEFAULT 0,       -- رصيد المخزن الحالي
    bin_location TEXT                       -- موقع التخزين (الرف / الدرج / العلبة)
);

-- 2. Devices Table (جدول الأجهزة واللوحات والشاسيهات)
CREATE TABLE IF NOT EXISTS devices (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    device_type TEXT NOT NULL,              -- نوع الجهاز (شاشة LED، خلاط، شاحن، ميكروويف)
    brand TEXT NOT NULL,                    -- الشركة المصنعة (LG, Samsung, Universal, Moulinex)
    model_number TEXT NOT NULL,             -- موديل الجهاز أو الشاسيه
    board_number TEXT                       -- كود اللوحة أو رقم الشاسيه (TP.MS338E.PB801, EAX68253901)
);

-- 3. Compatibilities Table (جدول الربط والتوافقية بين القطع والأجهزة)
CREATE TABLE IF NOT EXISTS compatibilities (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    component_id INTEGER NOT NULL REFERENCES components(id) ON DELETE CASCADE,
    device_id INTEGER NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    circuit_role TEXT,                      -- وظيفة القطعة بالدائرة (مذبذب الباور، موسفيت التقطيع)
    board_location TEXT,                    -- موقع القطعة على البوردة (IC901, UB101, QB101)
    technician_notes TEXT                   -- ملاحظات فنية خاصة بالصيانة والتعديل
);

-- 4. Equivalents Table (جدول البدائل والمكافئات المتوافقة)
CREATE TABLE IF NOT EXISTS equivalents (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    original_id INTEGER NOT NULL REFERENCES components(id) ON DELETE CASCADE,
    substitute_id INTEGER NOT NULL REFERENCES components(id) ON DELETE CASCADE,
    equivalence_type TEXT CHECK(equivalence_type IN ('Direct_Drop_In', 'Requires_Modification')),
    modification_instructions TEXT           -- إرشادات التعديل الفنية في حال اختلاف الأطراف أو القيم
);

-- =====================================================================
-- PERFORMANCE INDEXES (فهارس البحث الفوري عالي السرعة)
-- =====================================================================
CREATE INDEX IF NOT EXISTS idx_components_part_number ON components(part_number);
CREATE INDEX IF NOT EXISTS idx_components_category ON components(category);
CREATE INDEX IF NOT EXISTS idx_devices_model_number ON devices(model_number);
CREATE INDEX IF NOT EXISTS idx_devices_board_number ON devices(board_number);
CREATE INDEX IF NOT EXISTS idx_devices_brand ON devices(brand);
CREATE INDEX IF NOT EXISTS idx_compat_comp_id ON compatibilities(component_id);
CREATE INDEX IF NOT EXISTS idx_compat_dev_id ON compatibilities(device_id);
CREATE INDEX IF NOT EXISTS idx_equiv_orig_id ON equivalents(original_id);
CREATE INDEX IF NOT EXISTS idx_equiv_sub_id ON equivalents(substitute_id);

